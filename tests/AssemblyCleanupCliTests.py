"""Cleanup safety through the public compiler, using an isolated owned directory."""
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile


def invoke(executable, *arguments, success=True):
    result = subprocess.run([executable, *map(str, arguments)], capture_output=True, text=True)
    if success and result.returncode != 0:
        raise AssertionError(result.stdout + result.stderr)
    if not success and result.returncode == 0:
        raise AssertionError("Unexpected success: " + result.stdout)
    return json.loads(result.stdout) if result.stdout.strip() else None


def main():
    executable = str(Path(sys.argv[1]).resolve())
    with tempfile.TemporaryDirectory(prefix="zenasset-cleanup-") as temporary:
        root = Path(temporary)
        source = root / "model.obj"
        manifest = root / "build.json"
        output = root / "cooked"
        manifest.write_text(json.dumps({
            "version": 2, "outputDirectory": "cooked", "assembly": "scene.zenscene",
            "jobs": [{"key": "model", "source": "model.obj"}],
            "instances": [{"key": "one", "model": "model"}],
        }))

        def build(scale):
            source.write_text(f"v 0 0 0\nv {scale} 0 0\nv 0 1 0\nf 1 2 3\n")
            result = invoke(executable, "build", manifest)
            return Path(result["jobs"][0]["output"])

        first = build(1)
        retained = output / "retained.zenscene"
        shutil.copyfile(output / "scene.zenscene", retained)
        second = build(2)
        unknown = output / "models" / "user-owned.zenasset"
        unknown.write_bytes(b"not generated by the assembly builder")
        result = invoke(executable, "clean", output)
        assert result["dry_run"] and not result["candidates"] and not result["deleted"]
        assert first.exists() and second.exists() and unknown.exists()

        retained.unlink()
        result = invoke(executable, "clean", output)
        assert len(result["candidates"]) == 1 and not result["deleted"] and first.exists()
        result = invoke(executable, "clean", output, "--dry-run", "off")
        assert len(result["deleted"]) == 1 and not first.exists() and second.exists() and unknown.exists()

        third = build(3)
        malformed = output / "broken.zenscene"
        malformed.write_bytes(b"corrupt assembly")
        invoke(executable, "clean", output, "--dry-run", "off", success=False)
        assert second.exists() and third.exists()
        malformed.unlink()
        original = third.read_bytes()
        corrupted = bytearray(original)
        corrupted[-1] ^= 1
        third.write_bytes(corrupted)
        invoke(executable, "clean", output, "--dry-run", "off", success=False)
        assert second.exists()
        third.write_bytes(original)

        # Case-insensitive Windows references must retain the original-cased file.
        # Relocation is exercised by moving the entire cooked tree, without sources.
        moved = root / "relocated"
        output.rename(moved)
        source.unlink()
        result = invoke(executable, "clean", moved)
        assert len(result["candidates"]) == 1

        link = root / "linked"
        try:
            link.symlink_to(moved, target_is_directory=True)
        except OSError as error:
            print(f"Symlink fixture unavailable on this host: {error}")
        else:
            invoke(executable, "clean", link, "--dry-run", "off", success=False)
            assert (moved / "models" / second.name).exists()
            link.unlink()
        invoke(executable, "clean", moved, "--dry-run", "bad", success=False)
        print("Assembly cleanup CLI safety checks passed")


if __name__ == "__main__":
    main()
